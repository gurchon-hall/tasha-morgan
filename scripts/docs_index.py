"""Regenerate the README.md index of each rules-docs folder (docs/rulings,
docs/engine, docs/design) from its entries' front matter.

Usage:
    python scripts/docs_index.py           # rewrite the indexes
    python scripts/docs_index.py --check   # exit 1 if any index is stale
"""

import re
import sys
from dataclasses import dataclass
from pathlib import Path

DOCS = Path(__file__).resolve().parent.parent / "docs"

STATUSES = ("open", "resolved", "superseded")


@dataclass(frozen=True)
class Kind:
    prefix: str
    folder: str
    title: str
    intro: str
    template: str


KINDS = (
    Kind(
        prefix="RUL",
        folder="rulings",
        title="Rulings",
        intro=(
            "How a rule or a card text is read when the official sources do not\n"
            "settle it (CLAUDE.md §2). While an entry is `open`, the code path\n"
            'raises `UnresolvedRulingError("RUL-<nnn>")` or the card is blocked,\n'
            "until the user rules."
        ),
        template=(
            "Open: `Situation` / `Sources read` / `Candidate readings` /\n"
            "`Impacted code`. Resolved: exactly `Situation` /\n"
            "`Rules & interactions` / `Solution`."
        ),
    ),
    Kind(
        prefix="ENG",
        folder="engine",
        title="Engine mechanisms",
        intro=(
            "An engine mechanism a card needs (a hook, a subsystem), a gap in\n"
            "one, or an engine bug found in review. While an entry is `open`,\n"
            'the cards it impacts are blocked with `blocked_reason="ENG-<nnn>"`.'
        ),
        template=(
            "Open: `Situation` / `Sources read` / `Needed mechanism` /\n"
            "`Impacted code`. Resolved: exactly `Situation` /\n"
            "`Rules & interactions` / `Solution`."
        ),
    ),
    Kind(
        prefix="DES",
        folder="design",
        title="Design decisions",
        intro=(
            "Project, architecture and bot-strategy choices. These are design\n"
            "choices, not VtES facts."
        ),
        template="`Context` / `Decision` / `Consequence`.",
    ),
)

ENTRY_RE = re.compile(r"^(?P<id>(?P<prefix>RUL|ENG|DES)-(?P<num>\d{3}))-[a-z0-9-]+\.md$")
TITLE_RE = re.compile(r"^# (?P<id>(?:RUL|ENG|DES)-\d{3}) - (?P<title>.+)$", re.M)


@dataclass(frozen=True)
class Entry:
    id: str
    path: Path
    title: str
    status: str
    date: str
    cards: str
    superseded_by: str | None


def parse_front_matter(text: str) -> tuple[dict[str, str], str]:
    if not text.startswith("---\n"):
        raise ValueError("missing front matter")
    end = text.index("\n---\n", 4)
    fields: dict[str, str] = {}
    for line in text[4:end].splitlines():
        key, sep, value = line.partition(":")
        if not sep:
            raise ValueError(f"bad front matter line {line!r}")
        fields[key.strip()] = value.strip()
    return fields, text[end + 5 :]


def load_entries(kind: Kind) -> list[Entry]:
    entries = []
    for path in sorted((DOCS / kind.folder).glob(f"{kind.prefix}-*.md")):
        match = ENTRY_RE.match(path.name)
        if match is None:
            raise ValueError(f"{path}: file name must be <ID>-<slug>.md")
        fields, body = parse_front_matter(path.read_text(encoding="utf-8"))
        title = TITLE_RE.search(body)
        if title is None or title["id"] != match["id"]:
            raise ValueError(f"{path}: title must be '# {match['id']} - <title>'")
        status = fields.get("status", "")
        if status not in STATUSES:
            raise ValueError(f"{path}: status must be one of {STATUSES}")
        superseded_by = fields.get("superseded_by") or None
        if (status == "superseded") != (superseded_by is not None):
            raise ValueError(f"{path}: superseded_by is required exactly when superseded")
        entries.append(
            Entry(
                id=match["id"],
                path=path,
                title=title["title"],
                status=status,
                date=fields.get("date", ""),
                cards=fields.get("cards", ""),
                superseded_by=superseded_by,
            )
        )
    numbers = [int(e.id[4:]) for e in entries]
    if len(set(numbers)) != len(numbers):
        raise ValueError(f"{kind.folder}: duplicate {kind.prefix} number")
    return entries


def render_index(kind: Kind, entries: list[Entry]) -> str:
    lines = [
        f"# {kind.title} ({kind.prefix})",
        "",
        kind.intro,
        "",
        f"One file per entry: `{kind.prefix}-<nnn>-<slug>.md`, numbered from 001,",
        "never reused or renumbered. Front matter: `status` (`open` / `resolved`",
        "/ `superseded` + `superseded_by`), `date`, `cards` (semicolon-separated).",
        f"Body: {kind.template}",
        "",
        "Generated by `scripts/docs_index.py` -- do not edit by hand.",
        "",
        "<!-- pyml disable md013 -->",
        "",
        "| ID | Title | Status | Cards |",
        "| --- | --- | --- | --- |",
    ]
    for e in entries:
        status = f"superseded by {e.superseded_by}" if e.superseded_by else e.status
        title = e.title.replace("|", "\\|")
        cards = e.cards or "-"
        lines.append(f"| [{e.id}]({e.path.name}) | {title} | {status} | {cards} |")
    lines += ["", "<!-- pyml enable md013 -->"]
    return "\n".join(lines) + "\n"


def main(argv: list[str]) -> int:
    check = "--check" in argv
    stale = []
    for kind in KINDS:
        index = DOCS / kind.folder / "README.md"
        expected = render_index(kind, load_entries(kind))
        current = index.read_text(encoding="utf-8") if index.exists() else None
        if current == expected:
            continue
        if check:
            stale.append(str(index))
        else:
            index.write_text(expected, encoding="utf-8", newline="\n")
    if stale:
        print("stale index (run scripts/docs_index.py):", *stale, sep="\n  ")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
